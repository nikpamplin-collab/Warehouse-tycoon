import assert from 'node:assert/strict';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {test} from 'node:test';
import {boot,compile,setup} from './runtime.mjs';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const script=compile(root);
function fresh(seed=731){const g=boot(script,seed);setup(g);return g;}
const object=x=>JSON.parse(JSON.stringify(x));
const status='DOT20Fire.footprint(selectedSite())';
const tick='progress(state.player);state.month++;';
test('staged and paid orders cannot bypass commissioning, racking, cash or deduplication',()=>{
 const g=fresh(); const run=g.run;
 run("go('investment');selectedSite().racks=9;state.player.cash=200000");
 for(const kind of ['roof','rack'])run("orderFireProtection('"+kind+"')");
 assert.equal(run('selectedSite().projects.length'),0);
 run('state.player.cash=39999;orderFireProtection("tank")');
 assert.equal(run('selectedSite().projects.length'),0);
 assert.equal(run('state.player.cash'),39999);
 run("state.player.cash=200000;orderFireProtection('tank');orderFireProtection('tank');orderFireProtection('roof')");
 assert.equal(run('state.player.cash'),160000);
 assert.equal(run('selectedSite().projects.length'),1);
 assert.equal(run('dot16ViewModel().openCapitalOrders.cost'),40000);
 assert.match(run('warehouseGraphic(selectedSite())'),/d20-water-tank.*d20-pump-house/s);
 assert.match(run('warehouseGraphic(selectedSite())'),/Tank and pumps: fit-out/);
 assert.deepEqual(object(run(status)),{water:0,roof:0,rack:0});
 assert.equal(run('DOT20Fire.runningCost(selectedSite())'),0);
 run(tick);assert.equal(run(status+'.water'),0);
 run(tick);assert.equal(run(status+'.water'),1);
 assert.equal(run('DOT20Fire.runningCost(selectedSite())'),120);
 assert.equal(run('DOT20Fire.outcome(selectedSite(),40000,.3).cost'),40000);
 run("orderFireProtection('rack');orderFireProtection('roof')");
 assert.equal(run('state.player.cash'),122000);
 assert.match(run('warehouseGraphic(selectedSite())'),/d20-roof-pipework/);
 assert.equal(run(status+'.roof'),0);
 run(tick);assert.equal(run(status+'.roof'),0);
 run(tick);assert.equal(run(status+'.roof'),1);
 assert.equal(run('DOT20Fire.runningCost(selectedSite())'),180);
 run('selectedSite().racks=0;orderFireProtection("rack")');
 assert.equal(run('selectedSite().projects.length'),0);
 run("selectedSite().racks=9;orderFireProtection('rack');orderFireProtection('rack')");
 assert.equal(run('state.player.cash'),102000);
 assert.match(run('warehouseGraphic(selectedSite())'),/d20-rack-pipework/);
 assert.equal(run(status+'.rack'),0);
 run(tick);
 assert.deepEqual(object(run(status)),{water:1,roof:1,rack:1});
 assert.equal(run('DOT20Fire.runningCost(selectedSite())'),230);
 assert.match(run('warehouseGraphic(selectedSite())'),/In-rack pipework: commissioned/);
 assert.match(run('DOT20Fire.controls(selectedSite(),state.player.cash)'),/£230\/turn/);
 assert.equal(run('dot16ViewModel().openCapitalOrders'),undefined);
});
test('ignitions and safety event counts are unchanged, with graduated real loss and disruption',()=>{
 const g=fresh(399);const run=g.run;
 run(`Object.assign(selectedSite(),{staff:15,racks:9,managers:3,hs:true});
 selectedSite().contracts=[{start:1,end:24,spaces:2400,moves:12000,storage:17,handling:6}];
 Math.random=()=>.008;`);
 const unprotected=object(run('runSite(state.player,selectedSite(),1)'));
 assert.equal(unprotected.incident.kind,'Fire');
 assert.equal(unprotected.incident.severity,'Large');
 assert.ok(unprotected.incident.moves>0);
 run('selectedSite().fireProtection={water:1,roof:1,rack:0}');
 const roof=object(run('runSite(state.player,selectedSite(),1)'));
 run('selectedSite().fireProtection={water:1,roof:1,rack:1}');
 const rack=object(run('runSite(state.player,selectedSite(),1)'));
 assert.equal(roof.incident.kind,'Fire');
 assert.equal(rack.incident.kind,'Fire');
 assert.equal(roof.incident.severity,'Medium');
 assert.equal(rack.incident.severity,'Small');
 assert.equal(roof.incidentCost,Math.round(unprotected.incidentCost*.45));
 assert.equal(rack.incidentCost,Math.round(unprotected.incidentCost*.2));
 assert.ok(unprotected.incident.moves>roof.incident.moves&&roof.incident.moves>rack.incident.moves);
 assert.equal(rack.facilityCost,230);
 assert.match(run('incidentSummary({incidents:[selectedSite().last.incident]})'),/FIRE INCIDENT \(Small\)/);
 assert.deepEqual(object(run(`[false,true].map(protectedSite=>{
 const s={sections:1,racks:9,hs:true,fireProtection:protectedSite?{water:1,roof:1,rack:1}:null},out={Fire:0,Safety:0,clear:0};
 for(let i=0;i<10000;i++)out[DOT20Fire.incidentKind(s,(i+.5)/10000)||'clear']++;
 return out;
 })`)),[{Fire:120,Safety:880,clear:9000},{Fire:120,Safety:880,clear:9000}]);
 run('Math.random=()=>.99');
 const billed=object(run('companyMonth(state.player,state.month)'));
 assert.equal(billed.facilityCost,230);
 assert.match(run('history()'),/Facilities inspections.*−£230/s);
});
test('extensions do not inherit cover, and active and paid legacy installs migrate',()=>{
 const g=fresh(64);const run=g.run;
 run('Object.assign(selectedSite(),{sections:2,racks:9,facilitySprinklers:true});save()');
 const saved=boot(script,65,g.store);const old=saved.run;
 assert.deepEqual(object(old(status)),{water:2,roof:2,rack:0});
 assert.equal(old('Object.hasOwn(selectedSite(),"facilitySprinklers")'),false);
 old('selectedSite().sections=3');
 assert.equal(old('DOT20Fire.quote(selectedSite(),DOT20Fire.WATER).cost'),5000);
 assert.equal(old('DOT20Fire.quote(selectedSite(),DOT20Fire.ROOF).available'),false);
 assert.equal(old('DOT20Fire.outcome(selectedSite(),30000,.3).cost'),19000);
 old('orderFireProtection("tank");'+tick+tick);
 assert.equal(old('DOT20Fire.quote(selectedSite(),DOT20Fire.ROOF).cost'),38000);
 old('orderFireProtection("roof");'+tick+tick);
 assert.deepEqual(object(old(status)),{water:3,roof:3,rack:0});
 old('selectedSite().fireProtection=undefined;selectedSite().projects=[{type:"Sprinklers",remaining:1,cost:18000}];save();');
 const pending=boot(script,66,saved.store);
 assert.equal(pending.run('DOT20Fire.quote(selectedSite(),DOT20Fire.WATER).available'),false);
 const previous=pending.run('state.player.cash');
 pending.run(tick);
 assert.equal(pending.run('state.player.cash'),previous);
 assert.deepEqual(object(pending.run(status)),{water:3,roof:3,rack:0});
});

test('v20 backs up the configured save before migrating legacy protection',()=>{
 const g=boot(script,43);setup(g);
 g.run('delete state.player.sites[0].fireProtection;state.player.sites[0].facilitySprinklers=true;save()');
 const prior=g.store.get('warehouse_tycoon_v11');
 const old=new Map(g.store);old.delete('warehouse_tycoon_v11_pre_dotv20');
 const next=boot(script,45,old);
 assert.equal(old.get('warehouse_tycoon_v11_pre_dotv20'),prior);
 assert.equal(next.run('state.player.sites[0].fireProtection.roof'),1);
 assert.equal(next.run('state.player.sites[0].facilitySprinklers'),undefined);
});
