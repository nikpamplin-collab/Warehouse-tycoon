import assert from 'node:assert/strict';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {test} from 'node:test';
import {boot,compile,setup} from './runtime.mjs';

const script=compile(path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..'));
test('dock project capacity, affordability, accounting, graphic and reload remain independent of fire protection',()=>{
 const g=boot(script);setup(g);const run=g.run;
 run(`go('warehouse'); state.player.cash=200000;
 Object.assign(selectedSite(),{staff:15,racks:9,managers:3,hs:true});
 selectedSite().contracts=[{start:1,end:24,spaces:2500,moves:12500,storage:17,handling:6}];
 Math.random=()=>.99`);
 const basis='state.player,selectedSite(),state.month';
 const prev=run('DOT17Facilities.dockCapacity(selectedSite())');
 assert.equal(run('DOT17Facilities.doorCount(selectedSite())'),2);
 const base=JSON.parse(run(`JSON.stringify(runSite(${basis}))`));
 assert.equal(base.capacity,prev);
 assert.ok(base.missed>0);
 assert.equal(base.facilityCost,0);
 assert.match(run('DOT17Facilities.panel(selectedSite(),state.player.cash)'),/Add dock door.*£28,000/);
 assert.match(run('DOT17Facilities.panel(selectedSite(),100)'),/disabled[^>]*onclick="orderWarehouseFacility/);
 run(`orderWarehouseFacility('dock'); orderWarehouseFacility('dock');`);
 assert.equal(run('state.player.cash'),172000);
 assert.equal(run('selectedSite().projects.length'),1);
 assert.equal(run('siteCapacity(selectedSite())'),prev);
 assert.equal(run('dot16ViewModel().openCapitalOrders.cost'),28000);
 assert.match(run(`(visualSceneMode='build',warehouseGraphic(selectedSite()))`),/Dock door/);
 run('progress(state.player);state.month++');
 assert.equal(run('selectedSite().projects.length'),0);
 assert.equal(run('DOT17Facilities.doorCount(selectedSite())'),3);
 assert.ok(run('siteCapacity(selectedSite())')>prev);
 const after=JSON.parse(run(`JSON.stringify(runSite(${basis}))`));
 assert.ok(after.missed<base.missed);
 assert.equal(after.facilityCost,0);
 run('save()');
 const reload=boot(script,918,g.store);
 assert.equal(reload.run('state.player.sites[0].facilityDocks'),1);
 assert.equal(reload.run('state.player.sites[0].fireProtection'),undefined);
});
