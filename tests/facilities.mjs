import assert from 'node:assert/strict';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {boot,compile,setup} from './runtime.mjs';

const here=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const script=compile(here);
const g=boot(script);
setup(g);
const run=g.run;
assert.equal(run('DOT17Facilities.dockCapacity({sections:1})'),11000);
assert.equal(run('DOT17Facilities.dockCapacity({sections:2})'),22000);
assert.equal(run('DOT17Facilities.handlingCapacity({sections:1},7500)'),7500);
assert.equal(run('DOT17Facilities.handlingCapacity({sections:1},17500)'),11000);
assert.equal(run('DOT17Facilities.fireRisk({hs:true})'),.012);
assert.ok(Math.abs(run('DOT17Facilities.fireRisk({hs:true,facilitySprinklers:true})')-.0024)<1e-10);
assert.equal(run('DOT17Facilities.incidentKind({hs:true},.008)'),'Fire');
assert.equal(run('DOT17Facilities.incidentKind({hs:true,facilitySprinklers:true},.008)'),null);
assert.equal(run('DOT17Facilities.incidentKind({hs:true,facilitySprinklers:true},.001)'),'Fire');
assert.equal(run('DOT17Facilities.incidentKind({hs:true,facilitySprinklers:true},.08)'),'Safety');
assert.equal(run('DOT17Facilities.incidentKind({hs:true,facilitySprinklers:true},.3)'),null);
const frequencies=JSON.parse(run(`JSON.stringify([false,true].map(protectedSite=>{
 const s={hs:true,facilitySprinklers:protectedSite},out={Fire:0,Safety:0,clear:0};
 for(let i=0;i<10000;i++)out[DOT17Facilities.incidentKind(s,(i+.5)/10000)||'clear']++;
 return out;
}))`));
assert.deepEqual(frequencies,[{Fire:120,Safety:880,clear:9000},{Fire:24,Safety:880,clear:9096}]);

run(`go('warehouse'); state.player.cash=200000;
 Object.assign(selectedSite(),{staff:15,racks:9,managers:3,hs:true});
 selectedSite().contracts=[{start:1,end:24,spaces:2500,moves:12500,storage:17,handling:6}];
 Math.random=()=>.99`);
const scope='state.player,selectedSite(),state.month';
const base=JSON.parse(run(`JSON.stringify(runSite(${scope}))`));
assert.equal(base.capacity,11000);
assert.ok(base.missed>0,'Warehouse must be dock-constrained in fixture');
assert.equal(base.facilityCost,0);
assert.equal(run('(()=>{const s=state.rivals[0].sites[0]; s.staff=100;return siteCapacity(s)>DOT17Facilities.dockCapacity(s)})()'),true);
assert.match(run('DOT17Facilities.panel(selectedSite(),state.player.cash)'),/Add dock door.*£28,000/);
assert.match(run('DOT17Facilities.panel(selectedSite(),100)'),/disabled[^>]*onclick="orderWarehouseFacility/);

run(`orderWarehouseFacility('dock'); orderWarehouseFacility('dock'); orderWarehouseFacility('sprinklers'); orderWarehouseFacility('sprinklers');`);
assert.equal(run('state.player.cash'),154000);
assert.equal(run('selectedSite().projects.length'),2);
assert.match(run('DOT17Facilities.strip(selectedSite())'),/2 working dock doors.*1 in fit-out/s);
assert.match(run('DOT17Facilities.strip(selectedSite())'),/Sprinklers in fit-out/);
assert.equal(run('siteCapacity(selectedSite())'),11000);
assert.equal(run('dot16ViewModel().openCapitalOrders.cost'),46000);
assert.match(run(`(visualSceneMode='build',warehouseGraphic(selectedSite()))`),/Dock door.*Sprinklers/s);
run('progress(state.player);state.month++');
assert.equal(run('selectedSite().projects.length'),1);
assert.equal(run('siteCapacity(selectedSite())'),16500);
const afterDock=JSON.parse(run(`JSON.stringify(runSite(${scope}))`));
assert.equal(afterDock.facilityCost,0);
assert.ok(afterDock.handled>=12000);
assert.ok(afterDock.missed<base.missed); // Original contract-density ceiling still applies.
run('progress(state.player);state.month++');
assert.equal(run('selectedSite().projects.length'),0);
assert.match(run('DOT17Facilities.strip(selectedSite())'),/Sprinklers commissioned.*0.24% monthly fire risk/s);
assert.match(run(`(visualSceneMode='floor',warehouseGraphic(selectedSite()))`),/#83ccb7/);
const billed=JSON.parse(run('JSON.stringify(companyMonth(state.player,state.month))'));
assert.equal(billed.facilityCost,120);
const ops=(billed.mheCost||0)+(billed.stockControlCost||0)+(billed.stockFines||0);
assert.ok(Math.abs(billed.profit-(billed.storage+billed.handling-billed.rent-billed.labour-billed.hs-billed.incidentCost-billed.overflowCost-billed.interest-billed.management-billed.facilityCost-ops))<1e-7);
assert.match(run('history()'),/Facilities inspections.*−£120/s);
run(`Math.random=()=>.008; selectedSite().facilitySprinklers=false`);
const fire=JSON.parse(run(`JSON.stringify(runSite(${scope}))`));
assert.equal(fire.incident.kind,'Fire');
assert.ok(fire.incident.moves>0);
assert.equal(fire.incident.moves,fire.incident.recovered+fire.incident.netMissed);
assert.ok(fire.incidentCost>=24000);
assert.match(run(`incidentSummary({incidents:[selectedSite().last.incident]})`),/FIRE INCIDENT/);
run('selectedSite().facilitySprinklers=true');
assert.equal(run(`runSite(${scope}).incident`),null);
run('save()');
const reload=boot(script,918,g.store);
assert.equal(reload.run('state.player.sites[0].facilityDocks'),1);
assert.equal(reload.run('state.player.sites[0].facilitySprinklers'),true);
assert.equal(reload.run('state.player.last.facilityCost'),120);
console.log('PASS: dock bottleneck and commissioning, overspend/duplicates, sprinkler risk and billing, capex, site graphics, save/load');
